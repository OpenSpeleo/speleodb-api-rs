use syn::visit::Visit;
use syn::visit_mut::VisitMut;
use syn::{File, ImplItem, Item, Type, parse_quote};

const HEADER: &str = "// Generated by cargo xtask generate using openapi-to-rust. Do not edit.\n";
type Module = Vec<String>;

fn normalized(name: &str) -> String {
    name.chars()
        .filter(|c| c.is_ascii_alphanumeric())
        .flat_map(char::to_lowercase)
        .collect()
}

fn identifier(name: &str) -> String {
    let mut name = name.to_snake_case();
    if name.is_empty() || name.starts_with(|c: char| c.is_ascii_digit()) {
        name = format!("route_{name}");
    }
    if syn::parse_str::<syn::Ident>(&name).is_err() {
        name = format!("route_{name}");
    }
    name
}

fn route(path: &str, method: &str) -> Module {
    let mut segments: Vec<_> = path
        .split('/')
        .filter(|segment| !segment.is_empty())
        .map(|segment| {
            if segment.contains('{') {
                identifier(&format!("by_{}", segment.replace(['{', '}'], "")))
            } else {
                identifier(segment)
            }
        })
        .collect();
    segments.push(identifier(method));
    segments
}

fn item_name(item: &Item) -> Option<String> {
    match item {
        Item::Struct(item) => Some(item.ident.to_string()),
        Item::Enum(item) => Some(item.ident.to_string()),
        Item::Type(item) => Some(item.ident.to_string()),
        Item::Impl(item) => type_name(&item.self_ty),
        _ => None,
    }
}

fn declared_name(item: &Item) -> Option<String> {
    match item {
        Item::Fn(item) => Some(item.sig.ident.to_string()),
        Item::Const(item) => Some(item.ident.to_string()),
        Item::Mod(item) => Some(item.ident.to_string()),
        Item::Impl(_) => None,
        _ => item_name(item),
    }
}

fn exported_name(item: &Item) -> Option<String> {
    let visibility = match item {
        Item::Struct(item) => &item.vis,
        Item::Enum(item) => &item.vis,
        Item::Type(item) => &item.vis,
        Item::Fn(item) => &item.vis,
        Item::Const(item) => &item.vis,
        _ => return None,
    };
    if matches!(visibility, syn::Visibility::Public(_)) {
        declared_name(item)
    } else {
        None
    }
}

fn names(file: &File) -> BTreeSet<String> {
    fn use_names(tree: &syn::UseTree, output: &mut BTreeSet<String>) {
        match tree {
            syn::UseTree::Path(path) => use_names(&path.tree, output),
            syn::UseTree::Name(name) => {
                output.insert(name.ident.to_string());
            }
            syn::UseTree::Rename(name) => {
                output.insert(name.rename.to_string());
            }
            syn::UseTree::Group(group) => {
                for tree in &group.items {
                    use_names(tree, output);
                }
            }
            _ => {}
        }
    }
    let mut output: BTreeSet<_> = file.items.iter().filter_map(declared_name).collect();
    for item in &file.items {
        if let Item::Use(item) = item {
            use_names(&item.tree, &mut output);
        }
    }
    output
}

#[derive(Default)]
struct References(BTreeSet<String>);

struct ScalarParts<'a>(&'a BTreeSet<String>);
impl VisitMut for ScalarParts<'_> {
    fn visit_block_mut(&mut self, block: &mut syn::Block) {
        syn::visit_mut::visit_block_mut(self, block);
        let mut index = 0;
        while index + 2 < block.stmts.len() {
            let field = (|| {
                let syn::Stmt::Local(first) = &block.stmts[index] else {
                    return None;
                };
                let syn::Expr::Call(call) = &*first.init.as_ref()?.expr else {
                    return None;
                };
                let syn::Expr::Path(path) = &*call.func else {
                    return None;
                };
                if path.path.segments.last()?.ident != "bytes" {
                    return None;
                }
                let syn::Stmt::Local(second) = &block.stmts[index + 1] else {
                    return None;
                };
                let syn::Expr::Try(expression) = &*second.init.as_ref()?.expr else {
                    return None;
                };
                let syn::Expr::MethodCall(map_error) = &*expression.expr else {
                    return None;
                };
                let syn::Expr::MethodCall(mime) = &*map_error.receiver else {
                    return None;
                };
                if mime.method != "mime_str" {
                    return None;
                }
                let syn::Expr::Lit(literal) = mime.args.first()? else {
                    return None;
                };
                if !matches!(&literal.lit, syn::Lit::Str(value) if value.value() == "application/json")
                {
                    return None;
                }
                let syn::Stmt::Expr(syn::Expr::Assign(assignment), _) = &block.stmts[index + 2]
                else {
                    return None;
                };
                let syn::Expr::MethodCall(part) = &*assignment.right else {
                    return None;
                };
                if part.method != "part" {
                    return None;
                }
                let syn::Expr::Lit(literal) = part.args.first()? else {
                    return None;
                };
                let syn::Lit::Str(field) = &literal.lit else {
                    return None;
                };
                self.0.contains(&field.value()).then_some(field.clone())
            })();
            if let Some(field) = field {
                block.stmts.splice(index..index+3, [parse_quote!(form = form.part(#field, crate::form::multipart_scalar(value)?);)]);
            }
            index += 1;
        }
    }
}
impl References {
    fn tokens(&mut self, tokens: proc_macro2::TokenStream) {
        for token in tokens {
            match token {
                proc_macro2::TokenTree::Ident(ident) => {
                    self.0.insert(ident.to_string());
                }
                proc_macro2::TokenTree::Group(group) => self.tokens(group.stream()),
                proc_macro2::TokenTree::Literal(literal) => {
                    if let Ok(value) = syn::parse_str::<syn::LitStr>(&literal.to_string()) {
                        self.visit_lit_str(&value);
                    }
                }
                _ => {}
            }
        }
    }
}
impl<'ast> Visit<'ast> for References {
    fn visit_attribute(&mut self, attribute: &'ast syn::Attribute) {
        self.tokens(attribute.to_token_stream());
    }
    fn visit_macro(&mut self, value: &'ast syn::Macro) {
        self.tokens(value.to_token_stream());
    }
    fn visit_ident(&mut self, ident: &'ast syn::Ident) {
        self.0.insert(ident.to_string());
    }
    fn visit_lit_str(&mut self, literal: &'ast syn::LitStr) {
        // Serde codecs are referenced by string-valued attributes.
        self.0.extend(
            literal
                .value()
                .split(|c: char| !c.is_ascii_alphanumeric() && c != '_')
                .filter(|part| !part.is_empty())
                .map(str::to_owned),
        );
    }
}

fn type_name(ty: &Type) -> Option<String> {
    if let Type::Path(ty) = ty {
        ty.path
            .segments
            .last()
            .map(|segment| segment.ident.to_string())
    } else {
        None
    }
}

fn configure_default_transport(
    method: &mut syn::ImplItemFn,
    timeout_seconds: Option<u64>,
) -> Result<()> {
    fn path_is(expression: &syn::Expr, expected: &[&str]) -> bool {
        let syn::Expr::Path(path) = expression else {
            return false;
        };
        path.qself.is_none()
            && path.path.segments.len() == expected.len()
            && path
                .path
                .segments
                .iter()
                .zip(expected)
                .all(|(segment, name)| {
                    segment.ident == *name && matches!(segment.arguments, syn::PathArguments::None)
                })
    }

    let [syn::Stmt::Expr(syn::Expr::Call(constructor), None)] = method.block.stmts.as_slice()
    else {
        bail!("Upstream default HTTP constructor shape changed");
    };
    ensure!(
        constructor.args.len() == 1 && path_is(&constructor.func, &["Self", "with_client"]),
        "Upstream default HTTP constructor shape changed"
    );
    let Some(syn::Expr::Call(transport)) = constructor.args.first() else {
        bail!("Upstream default HTTP transport shape changed");
    };
    ensure!(
        transport.args.is_empty() && path_is(&transport.func, &["reqwest", "Client", "new"]),
        "Upstream default HTTP transport shape changed"
    );
    let builder: syn::Expr = match timeout_seconds {
        Some(seconds) => parse_quote!(reqwest::Client::builder()
            .redirect(reqwest::redirect::Policy::none())
            .timeout(std::time::Duration::from_secs(#seconds))),
        None => {
            parse_quote!(reqwest::Client::builder().redirect(reqwest::redirect::Policy::none()))
        }
    };
    method.block = parse_quote!({
        Self::with_client(
            #builder
                .build()
                .expect("Failed to initialize the default SpeleoDB HTTP transport"),
        )
    });
    Ok(())
}

fn classify(
    name: &str,
    operations: &[(String, Module)],
    models: &[(String, String)],
    is_types: bool,
) -> Module {
    let compact = normalized(name);
    if let Some((_, module)) = operations
        .iter()
        .find(|(prefix, _)| compact.starts_with(prefix))
    {
        return module.clone();
    }
    if is_types {
        let model = models
            .iter()
            .find(|(prefix, _)| compact.starts_with(prefix))
            .map(|(_, name)| name.clone())
            .unwrap_or_else(|| identifier(name));
        let category = identifier(model.split('_').next().unwrap_or("shared"));
        return vec!["models".into(), category, model];
    }
    vec![]
}

fn write_modules(
    base: &str,
    file: File,
    groups: BTreeMap<Module, Vec<Item>>,
    artifacts: &mut BTreeMap<PathBuf, String>,
    available: &BTreeSet<String>,
) -> Result<()> {
    let mut children: BTreeMap<Module, std::collections::BTreeSet<String>> = BTreeMap::new();
    let mut exports: BTreeMap<Module, BTreeSet<String>> = BTreeMap::new();
    for (module, items) in &groups {
        let names: BTreeSet<_> = items.iter().filter_map(exported_name).collect();
        for depth in 0..=module.len() {
            exports
                .entry(module[..depth].to_vec())
                .or_default()
                .extend(names.iter().cloned());
        }
    }
    for module in groups.keys() {
        for depth in 0..module.len() {
            children
                .entry(module[..depth].to_vec())
                .or_default()
                .insert(module[depth].clone());
        }
    }
    let mut nodes: std::collections::BTreeSet<Module> = groups.keys().cloned().collect();
    nodes.extend(children.keys().cloned());
    nodes.insert(vec![]);
    for module in nodes {
        let mut output = File {
            shebang: None,
            frontmatter: None,
            attrs: if module.is_empty() {
                file.attrs.clone()
            } else {
                vec![]
            },
            items: vec![],
        };
        if let Some(items) = groups.get(&module) {
            if !module.is_empty() {
                let local: BTreeSet<_> = items.iter().filter_map(declared_name).collect();
                let mut references = References::default();
                for item in items {
                    references.visit_item(item);
                }
                let imports: Vec<_> = references
                    .0
                    .intersection(available)
                    .filter(|name| !local.contains(*name))
                    .collect();
                if !imports.is_empty() {
                    let prefix = "super::".repeat(module.len());
                    let import: Item = syn::parse_str(&format!(
                        "use {prefix}{{{}}};",
                        imports
                            .iter()
                            .map(|name| name.as_str())
                            .collect::<Vec<_>>()
                            .join(",")
                    ))?;
                    output.items.push(import);
                }
            }
            output.items.extend(items.clone());
        }
        if let Some(names) = children.get(&module) {
            for name in names {
                let ident: syn::Ident = syn::parse_str(name)?;
                output.items.push(parse_quote!(pub mod #ident;));
                let mut child = module.clone();
                child.push(name.clone());
                if let Some(names) = exports.get(&child).filter(|names| !names.is_empty()) {
                    let names: Vec<syn::Ident> = names
                        .iter()
                        .map(|name| syn::parse_str(name))
                        .collect::<syn::Result<_>>()?;
                    output
                        .items
                        .push(parse_quote!(pub use self::#ident::{#(#names),*};));
                }
            }
        }
        let directory: PathBuf = std::iter::once(base)
            .chain(module.iter().map(String::as_str))
            .collect();
        let path = if module.is_empty() || children.contains_key(&module) {
            directory.join("mod.rs")
        } else {
            directory.with_extension("rs")
        };
        ensure!(
            artifacts
                .insert(path, format!("{HEADER}{}", prettyplease::unparse(&output)))
                .is_none(),
            "Generated module collision"
        );
    }
    Ok(())
}

pub fn partition(
    artifacts: &mut BTreeMap<PathBuf, String>,
    schema_names: &[String],
    text_forms: &BTreeSet<String>,
    scalar_forms: &BTreeMap<String, BTreeSet<String>>,
    default_timeout_seconds: Option<u64>,
) -> Result<()> {
    let bindings = artifacts
        .remove(&PathBuf::from("bindings.json"))
        .context("Missing binding metadata")?;
    let metadata: Value = serde_json::from_str(&bindings)?;
    let symbols = metadata["symbols"]
        .as_array()
        .context("Missing binding symbols")?;
    let mut operations = BTreeMap::new();
    let mut text_methods = BTreeSet::new();
    let mut scalar_methods = BTreeMap::new();
    for symbol in symbols {
        if let Some(operation) = symbol.get("operation").filter(|value| value.is_object()) {
            if symbol["path"]
                .as_str()
                .is_some_and(|path| path.starts_with("client::HttpClient::"))
                && symbol["signature"]["asynchronous"].as_bool() == Some(true)
                && let Some(fields) = operation["operation_id"]
                    .as_str()
                    .and_then(|id| scalar_forms.get(id))
            {
                scalar_methods.insert(
                    symbol["name"]
                        .as_str()
                        .context("Missing method name")?
                        .to_owned(),
                    fields,
                );
            }
            if text_forms.contains(
                operation["operation_id"]
                    .as_str()
                    .context("Missing operationId")?,
            ) && symbol["path"]
                .as_str()
                .is_some_and(|path| path.starts_with("client::HttpClient::"))
                && symbol["signature"]["asynchronous"].as_bool() == Some(true)
            {
                text_methods.insert(
                    symbol["name"]
                        .as_str()
                        .context("Missing method name")?
                        .to_owned(),
                );
            }
            let id = operation["source_operation_id"]
                .as_str()
                .context("Missing source operationId")?;
            let module = route(
                operation["source_path"]
                    .as_str()
                    .context("Missing source path")?,
                operation["source_method"]
                    .as_str()
                    .context("Missing source method")?,
            );
            operations.insert(normalized(id), module);
        }
    }
    let mut operations: Vec<_> = operations.into_iter().collect();
    operations.sort_by(|a, b| b.0.len().cmp(&a.0.len()).then(a.0.cmp(&b.0)));
    let mut models: Vec<_> = schema_names
        .iter()
        .map(|name| (normalized(name), identifier(name)))
        .collect();
    models.sort_by(|a, b| b.0.len().cmp(&a.0.len()).then(a.0.cmp(&b.0)));
    let type_ast = syn::parse_file(
        artifacts
            .get(&PathBuf::from("types.rs"))
            .context("Missing types")?,
    )?;
    let type_names: BTreeSet<_> = type_ast
        .items
        .iter()
        .filter_map(|item| match item {
            Item::Struct(item) if matches!(item.vis, syn::Visibility::Public(_)) => {
                Some(item.ident.to_string())
            }
            Item::Enum(item) if matches!(item.vis, syn::Visibility::Public(_)) => {
                Some(item.ident.to_string())
            }
            Item::Type(item) if matches!(item.vis, syn::Visibility::Public(_)) => {
                Some(item.ident.to_string())
            }
            _ => None,
        })
        .collect();
    let mut top_exports = BTreeMap::new();
    let mut configured_constructors = 0;
    for name in ["client", "types"] {
        let original = artifacts
            .remove(&PathBuf::from(format!("{name}.rs")))
            .context("Missing generated Rust")?;
        let mut file = syn::parse_file(&original)?;
        top_exports.insert(
            name,
            file.items
                .iter()
                .filter_map(exported_name)
                .collect::<BTreeSet<_>>(),
        );
        let mut available = names(&file);
        if name == "client" {
            available.extend(type_names.iter().cloned());
        }
        let mut groups: BTreeMap<Module, Vec<Item>> = BTreeMap::new();
        for item in std::mem::take(&mut file.items) {
            if let Item::Impl(mut implementation) = item {
                if implementation.trait_.is_none()
                    && type_name(&implementation.self_ty).as_deref() == Some("HttpClient")
                {
                    let members = std::mem::take(&mut implementation.items);
                    let mut methods: BTreeMap<Module, Vec<ImplItem>> = BTreeMap::new();
                    for mut member in members {
                        if let ImplItem::Fn(method) = &mut member
                            && method.sig.ident == "new"
                        {
                            configure_default_transport(method, default_timeout_seconds)?;
                            configured_constructors += 1;
                        }
                        if let ImplItem::Fn(method) = &mut member
                            && let Some(fields) = scalar_methods.get(&method.sig.ident.to_string())
                        {
                            ScalarParts(fields).visit_block_mut(&mut method.block);
                        }
                        if let ImplItem::Fn(method) = &mut member
                            && text_methods.contains(&method.sig.ident.to_string())
                        {
                            let returns: Vec<_> = method
                                .block
                                .stmts
                                .iter()
                                .enumerate()
                                .filter_map(|(index, statement)| {
                                    matches!(statement, syn::Stmt::Expr(syn::Expr::Return(_), _))
                                        .then_some(index)
                                })
                                .collect();
                            ensure!(
                                returns.len() == 1,
                                "Upstream multipart fallback shape changed"
                            );
                            method.block.stmts[returns[0]] = parse_quote!(req = req.multipart(crate::form::multipart_text_fields(&request)?););
                        }
                        let module = if let ImplItem::Fn(method) = &member {
                            classify(&method.sig.ident.to_string(), &operations, &models, false)
                        } else {
                            vec![]
                        };
                        methods.entry(module).or_default().push(member);
                    }
                    for (module, members) in methods {
                        let mut block = implementation.clone();
                        block.items = members;
                        groups.entry(module).or_default().push(Item::Impl(block));
                    }
                } else {
                    let item = Item::Impl(implementation);
                    let module = item_name(&item)
                        .map(|name_| classify(&name_, &operations, &models, name == "types"))
                        .unwrap_or_default();
                    groups.entry(module).or_default().push(item);
                }
            } else {
                let module = item_name(&item)
                    .map(|name_| classify(&name_, &operations, &models, name == "types"))
                    .unwrap_or_default();
                groups.entry(module).or_default().push(item);
            }
        }
        write_modules(name, file, groups, artifacts, &available)?;
    }
    ensure!(
        configured_constructors == 1,
        "Expected exactly one default HTTP constructor for the transport policy"
    );
    let root_key = PathBuf::from("mod.rs");
    let mut root_file = syn::parse_file(
        artifacts
            .get(&root_key)
            .context("Missing generated module root")?,
    )?;
    for item in &mut root_file.items {
        if let Item::Use(usage) = item
            && let syn::UseTree::Path(path) = &usage.tree
            && matches!(*path.tree, syn::UseTree::Glob(_))
            && let Some(names) = top_exports.get(path.ident.to_string().as_str())
        {
            let module = &path.ident;
            let names: Vec<syn::Ident> = names
                .iter()
                .map(|name| syn::parse_str(name))
                .collect::<syn::Result<_>>()?;
            *item = parse_quote!(pub use self::#module::{#(#names),*};);
        }
    }
    artifacts.insert(
        root_key,
        format!("{HEADER}{}", prettyplease::unparse(&root_file)),
    );
    // Metadata follows the same route/resource tree, with shared symbols under
    // their named model. The index retains upstream metadata and lists shards.
    let mut shards: BTreeMap<Module, Vec<Value>> = BTreeMap::new();
    for symbol in symbols {
        let mut module =
            if let Some(operation) = symbol.get("operation").filter(|value| value.is_object()) {
                route(
                    operation["source_path"]
                        .as_str()
                        .context("Missing source path")?,
                    operation["source_method"]
                        .as_str()
                        .context("Missing source method")?,
                )
            } else {
                let owner = symbol["path"]
                    .as_str()
                    .and_then(|path| path.split("::").nth(1))
                    .or_else(|| symbol["name"].as_str())
                    .unwrap_or("shared");
                classify(owner, &operations, &models, true)
            };
        if module.is_empty() {
            module.push("shared".into());
        }
        shards.entry(module).or_default().push(symbol.clone());
    }
    let mut filenames = Vec::new();
    for (module, symbols) in shards {
        let path: PathBuf = module.iter().collect();
        let path = path.with_extension("json");
        filenames.push(path.to_string_lossy().replace('\\', "/"));
        artifacts.insert(
            PathBuf::from("bindings").join(path),
            format!("{}\n", serde_json::to_string_pretty(&symbols)?),
        );
    }
    let mut index = metadata.clone();
    index.as_object_mut().unwrap().remove("symbols");
    index["symbol_files"] = serde_json::to_value(filenames)?;
    artifacts.insert(
        PathBuf::from("bindings/index.json"),
        format!("{}\n", serde_json::to_string_pretty(&index)?),
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_transport_rejects_changed_upstream_initialization() {
        let mut method: syn::ImplItemFn = parse_quote! {
            pub fn new() -> Self {
                Self::with_config(None, true)
            }
        };
        assert!(configure_default_transport(&mut method, Some(30)).is_err());
        assert!(configure_default_transport(&mut method, None).is_err());
    }
}
